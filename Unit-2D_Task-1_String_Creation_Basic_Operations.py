# String Creation
str1 = "Hello"
str2 = "Python"

print("String 1:", str1)
print("String 2:", str2)

# Concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# Repetition
result = str1 * 3
print("Repetition:", result)

# Slicing
result = str2[0:3]
print("Slicing:", result)